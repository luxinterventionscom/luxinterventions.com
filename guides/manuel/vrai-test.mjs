// Prova ⭐ « Vrai — à conserver » e 🧹 pulizia dei dati di prova : WORKER_MJS=… node vrai-test.mjs
import { chromium } from 'playwright';
import { writeFile } from 'node:fs/promises';
import { execFileSync } from 'node:child_process';
import { phone, centralSetup, assert, log } from './harness.mjs';
const PASS = 'Tr3s-l0ngue-cle!';
const b = await chromium.launch(), errs = [];
const act = (p, a, d = {}) => p.evaluate(([a, d]) => { const el = document.createElement('button'); el.dataset.action = a; Object.assign(el.dataset, d); el.hidden = true; document.body.append(el); el.click(); el.remove(); }, [a, d]);
const demo = new URL('./shots/demo.json', import.meta.url).pathname;
await writeFile(demo, execFileSync('node', [new URL('./demo-data.mjs', import.meta.url).pathname]));
const c = await phone(b, 'it', { width: 1000, height: 900 }), p = await c.newPage(); p.on('pageerror', (e) => errs.push(e.message));
await centralSetup(p);
await p.evaluate(() => { location.hash = '#/reglages'; }); await p.waitForTimeout(900);
const [fc] = await Promise.all([p.waitForEvent('filechooser'), act(p, 'import')]);
await fc.setFiles(demo); await p.waitForTimeout(800); await p.click('#confirm button[type=submit], #confirm .btn.primary'); await p.waitForTimeout(2500);
// ⭐ Anna (locataire) e Luc (operaio)
await act(p, 'open-loc', { id: 'lc1' }); await p.waitForTimeout(700);
await p.click('.sheet .vrai'); await p.waitForTimeout(800);
assert((await p.$eval('.sheet .vrai', (e) => e.textContent)).includes('⭐'), 'Anna segnata ⭐');
await p.keyboard.press('Escape'); await p.waitForTimeout(400);
await act(p, 'open-interv', { id: 'w1' }); await p.waitForTimeout(700);
await p.click('.sheet .vrai'); await p.waitForTimeout(800);
await p.keyboard.press('Escape'); await p.waitForTimeout(400);
await act(p, 'test-clean'); await p.waitForTimeout(800);
const sh = await p.$eval('.sheet', (e) => e.innerText);
assert(/Anna/.test(sh) && /Luc/.test(sh) && /12, rue des Exemples/.test(sh), 'lista «gardé»: Anna, Luc, il suo immobile');
log('piano di pulizia mostrato');
const [dl] = await Promise.all([p.waitForEvent('download'), p.click('[data-action=test-clean-do]')]);
assert(/avant_nettoyage/.test(dl.suggestedFilename()), 'backup automatico scaricato: ' + dl.suggestedFilename());
await p.waitForTimeout(600);
await p.fill('#confirm input[name=k]', PASS); await p.click('#confirm button[type=submit]'); await p.waitForTimeout(3000);
await p.evaluate(() => { location.hash = '#/locataires'; }); await p.waitForTimeout(1200);
const lt = await p.evaluate(() => document.body.innerText);
assert(/Martin/.test(lt) && !/Silva|Weber|Rossi/.test(lt), 'resta solo Anna Martin tra gli inquilini');
await p.evaluate(() => { location.hash = '#/maintenance'; }); await p.waitForTimeout(1200);
await act(p, 'open-interv', { id: 'w1' }); await p.waitForTimeout(600);
assert(await p.$('.sheet'), 'Luc ancora presente');
await p.keyboard.press('Escape'); await p.waitForTimeout(300);
await act(p, 'open-interv', { id: 'w2' }); await p.waitForTimeout(600);
assert(!(await p.$('.sheet[open]')) || !(await p.$eval('.sheet', (e) => /Sofia/.test(e.innerText))), 'Sofia (prova) cancellata');
log('pulizia fatta: veri gardati, prova cancellata');
console.log('ERRORS', errs.length ? errs : 'none');
await b.close();
