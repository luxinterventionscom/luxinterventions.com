// App LuxInterventions (app.html) : demande → photo → envoi, devis signé, sauvegarde/import.
// Avant : (cd ../.. && python3 -m http.server 8766) · puis : node luxapp-test.cjs <dossier pour les captures>
const { chromium, devices } = require('playwright');
const fs = require('fs');
const S = process.argv[2];
(async () => {
  const b = await chromium.launch();
  const c = await b.newContext({ ...devices['iPhone 13'], permissions: ['clipboard-read', 'clipboard-write'] });
  const p = await c.newPage(); const errs = []; let ups = 0;
  p.on('pageerror', (e) => errs.push(e.message)); p.on('console', (m) => { if (m.type() === 'error') errs.push('console: ' + m.text()); });
  await p.route('https://luxinterventions-hitcounter.weathered-tree-cfd3.workers.dev/**', (r) => { ups++; r.fulfill({ status: 200, contentType: 'application/json', headers: { 'access-control-allow-origin': '*' }, body: JSON.stringify({ url: 'https://photos.example/' + ups + '.jpg' }) }); });
  await p.goto('http://localhost:8766/app.html'); await p.waitForTimeout(800);
  const ok = (cond, m) => { console.log((cond ? 'OK  ' : 'FAIL ') + m); if (!cond) process.exitCode = 1; };
  ok(await p.$$eval('.tile', (x) => x.length) === 12, '12 mattonelle');
  await p.screenshot({ path: S + '/a1.png' });
  await p.click('[data-k=plomb]'); await p.waitForTimeout(300);
  await p.click('[data-act=next1]'); ok(await p.isVisible('#toast'), 'blocca senza statut/nome');
  await p.click('[data-seg=statut] [data-v=locataire]'); await p.fill('#f-nom', 'Marie Test'); await p.fill('#f-tel', '+352 600 000 000');
  await p.click('[data-act=next1]'); await p.waitForTimeout(300);
  await p.fill('#f-adr', '12 rue Test, L-1234 Luxembourg'); await p.fill('#f-notes', 'Fuite sous l’évier');
  const png = Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAYAAAAfFcSJAAAADUlEQVR42mP8z8BQDwAEhQGAhKmMIQAAAABJRU5ErkJggg==', 'base64');
  fs.writeFileSync(S + '/p.png', png);
  await p.setInputFiles('[data-in=photo]', S + '/p.png'); await p.waitForTimeout(600);
  ok(await p.$$eval('.ph img', (x) => x.length) === 1, 'foto aggiunta');
  await p.screenshot({ path: S + '/a2.png' });
  await p.click('[data-act=next2]'); await p.waitForTimeout(800);
  ok(/#\/f\/3/.test(p.url()) && ups === 1, 'passo 3, foto caricata sul Worker');
  await p.screenshot({ path: S + '/a3.png' });
  await p.click('[data-act=send][data-via=copie]'); await p.waitForTimeout(900);
  const clip = await p.evaluate(() => navigator.clipboard.readText());
  ok(/Plomberie/.test(clip) && /Marie Test/.test(clip) && /photos.example\/1.jpg/.test(clip), 'testo copiato con servizio, nome, link foto');
  ok(/#\/r\//.test(p.url()), 'va alla scheda della richiesta');
  await p.click('text=J’ai reçu un devis'); await p.waitForTimeout(300);
  await p.fill('#f-dno', 'D-0042');
  await p.setInputFiles('input[data-in=devis][accept="image/*"]', S + '/p.png'); await p.waitForTimeout(700);
  ok(/signer$/.test(p.url()), 'schermata firma');
  await p.$eval('#sig', (e) => e.scrollIntoView({ block: 'center' })); await p.waitForTimeout(200);
  const box = await p.$('#sig canvas'), bb = await box.boundingBox();
  await p.mouse.move(bb.x + 20, bb.y + 40); await p.mouse.down(); await p.mouse.move(bb.x + 120, bb.y + 80, { steps: 8 }); await p.mouse.move(bb.x + 200, bb.y + 30, { steps: 8 }); await p.mouse.up();
  await p.screenshot({ path: S + '/a6.png' });
  await p.click('[data-act=sign]'); await p.waitForTimeout(900);
  ok(ups === 3, 'firma + foto devis caricate (' + ups + ')');
  ok(/Signé/.test(await p.textContent('main')), 'stato Signé');
  await p.click('[data-act=resend-sig][data-via=copie]'); await p.waitForTimeout(500);
  const clip2 = await p.evaluate(() => navigator.clipboard.readText());
  ok(/BON POUR ACCORD/.test(clip2) && /D-0042/.test(clip2) && /photos.example\/2/.test(clip2), 'testo devis firmato');
  await p.goto('http://localhost:8766/app.html#/mes'); await p.waitForTimeout(500);
  ok((await p.$$('.row')).length === 1, 'Mes demandes: 1');
  await p.screenshot({ path: S + '/a5.png' });
  await p.goto('http://localhost:8766/app.html#/moi'); await p.waitForTimeout(400);
  const [dl] = await Promise.all([p.waitForEvent('download'), p.click('[data-act=backup]')]);
  await dl.saveAs(S + '/bk.json');
  await p.screenshot({ path: S + '/a7.png' });
  await p.evaluate(() => localStorage.clear()); await p.reload(); await p.waitForTimeout(400);
  await p.goto('http://localhost:8766/app.html#/moi'); await p.waitForTimeout(300);
  await p.setInputFiles('input[data-in=import]', S + '/bk.json'); await p.waitForTimeout(500);
  await p.goto('http://localhost:8766/app.html#/mes'); await p.waitForTimeout(400);
  ok((await p.$$('.row')).length === 1, 'import: richiesta ritrovata');
  console.log('ERRORS', errs.length ? errs : 'none');
  await b.close();
})();
